"""Generate the JSBSim matched-model F-16 (PRD 8.6) from data/f16/f16_sl.toml.

Writes <root>/{aircraft/f16_sl/f16_sl.xml, engine/dummy.xml, engine/direct.xml, planet/flat_nonrot.xml}.
CLI: python -m jsbsim_compare.gen_xml [--root reference/jsbsim] [--xcg 0.35]
"""
import argparse
import tomllib
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
TOML = REPO / "data/f16/f16_sl.toml"
# JSBSim converts emptywt (lbf) to slugs with 1/32.174049; calibrated, asserted to 1e-9 in test_gen_xml.py.
LBF_PER_SLUG = 32.174049
# Planet (PRD 8.6 / plan 6.2): spherical, non-rotating, WGS84 equatorial radius, GM chosen so g(0) = 9.80665 m/s^2.
R_FT = 20925646.32546
G0_FPS2 = 9.80665 / 0.3048
GM_FT3PS2 = G0_FPS2 * R_FT**2
# Surface travel mapped to the +-1 FCS command range (actuators.* position limits in the TOML).
IN_PER_FT = 12.0


def _f(x):
    return repr(float(x))


def _table(name, rows_ax, cols_ax, values, row_var, col_var=None):
    """Named JSBSim table function. 1-D when cols_ax is None (values is a flat list)."""
    if cols_ax is None:
        body = "".join(f"      {_f(a)} {_f(v)}\n" for a, v in zip(rows_ax, values))
        ind = f'<independentVar lookup="row">{row_var}</independentVar>'
    else:
        body = "      " + " ".join(_f(c) for c in cols_ax) + "\n"
        body += "".join(f"      {_f(a)} " + " ".join(_f(v) for v in row) + "\n" for a, row in zip(rows_ax, values))
        ind = (f'<independentVar lookup="row">{row_var}</independentVar>\n'
               f'    <independentVar lookup="column">{col_var}</independentVar>')
    return (f'  <function name="{name}">\n   <table>\n    {ind}\n    <tableData>\n{body}    </tableData>\n   </table>\n  </function>\n')


def _prod(*xs):
    return "<product>" + "".join(xs) + "</product>"


def _sum(*xs):
    return "<sum>" + "".join(xs) + "</sum>"


def _p(name):
    return f"<property>{name}</property>"


def _v(x):
    return f"<value>{_f(x)}</value>"


def _surface(ch, label, limit):
    """cmd + trim -> clipped sum -> degrees; output property aero/<ch>-fcs-deg."""
    return (f'   <summer name="{label}-sum"><input>fcs/{label}-cmd-norm</input><input>fcs/{ch}-trim-cmd-norm</input>'
            f'<clipto><min>-1</min><max>1</max></clipto></summer>\n'
            f'   <aerosurface_scale name="{label}">\n    <input>fcs/{label}-sum</input><domain><min>-1</min><max>1</max></domain>\n'
            f'    <range><min>{-limit}</min><max>{limit}</max></range><output>aero/{label}-fcs-deg</output>\n   </aerosurface_scale>\n')


def aircraft_xml(d, xcg):
    mg = {k: v["value"] for k, v in d["mass_geometry"].items()}
    A, E = d["aero"], d["engine"]
    cbar_in = mg["cbar"] * IN_PER_FT
    mass = 1.0 / mg["reciprocal_mass"]
    lim = {k: d["actuators"][k]["position_limits"][1] for k in ("elevator", "aileron", "rudder")}
    al = A["cx"]["alpha"]
    s = []
    s.append('<?xml version="1.0"?>\n<!-- GENERATED by python/jsbsim_compare/gen_xml.py from data/f16/f16_sl.toml. Do not edit. -->\n')
    s.append('<fdm_config name="f16_sl" version="2.0" release="ALPHA">\n')
    s.append(' <fileheader><author>flightsim gen_xml</author><description>S&amp;L low-fidelity F-16, matched model for PRD 8.6</description></fileheader>\n')
    s.append(f' <metrics>\n  <wingarea unit="FT2">{_f(mg["S"])}</wingarea>\n  <wingspan unit="FT">{_f(mg["b"])}</wingspan>\n  <chord unit="FT">{_f(mg["cbar"])}</chord>\n'
             f'  <location name="AERORP" unit="IN"><x>{_f(mg["xcg_ref"] * cbar_in)}</x><y>0</y><z>0</z></location>\n'
             '  <location name="EYEPOINT" unit="IN"><x>0</x><y>0</y><z>0</z></location>\n'
             '  <location name="VRP" unit="IN"><x>0</x><y>0</y><z>0</z></location>\n </metrics>\n')
    cg = f'<x>{_f(xcg * cbar_in)}</x><y>0</y><z>0</z>'
    s.append(f' <mass_balance negated_crossproduct_inertia="false">\n  <ixx unit="SLUG*FT2">{_f(mg["Ixx"])}</ixx>\n  <iyy unit="SLUG*FT2">{_f(mg["Iyy"])}</iyy>\n'
             f'  <izz unit="SLUG*FT2">{_f(mg["Izz"])}</izz>\n  <ixz unit="SLUG*FT2">{_f(mg["Ixz"])}</ixz>\n'
             f'  <emptywt unit="LBS">{_f(mass * LBF_PER_SLUG)}</emptywt>\n  <location name="CG" unit="IN">{cg}</location>\n </mass_balance>\n')
    s.append(' <ground_reactions/>\n')
    s.append(f' <propulsion>\n  <engine file="dummy"><thruster file="direct"><location unit="IN">{cg}</location></thruster></engine>\n </propulsion>\n')
    s.append(' <flight_control name="FCS">\n')
    for n in ("de", "da", "dr"):  # direct surface drive (deg): user properties no component writes
        s.append(f'  <property value="0">aero/{n}-direct-deg</property>\n')
    s.append('  <channel name="surfaces">\n')
    s.append(_surface("pitch", "elevator", lim["elevator"]) + _surface("roll", "aileron", lim["aileron"]) + _surface("yaw", "rudder", lim["rudder"]))
    s.append('  </channel>\n </flight_control>\n')
    # thrust: power-level interpolation of idle/military/maximum at (h, Mach), power from throttle gearing
    g = E["throttle_gearing"]
    thr = _p("fcs/throttle-cmd-norm[0]")
    power = ("<ifthen><le>" + thr + _v(g["breakpoint"]) + "</le>" + _prod(_v(g["low_slope"]), thr)
             + _sum(_prod(_v(g["high_slope"]), thr), _v(g["high_intercept"])) + "</ifthen>")
    t = {k: _p("thrust/table/" + k) for k in ("idle", "military", "maximum")}
    pp = _p("thrust/power-pct")
    lo = _sum(t["idle"], _prod(_sum(t["military"], _prod(_v(-1), t["idle"])), pp, _v(1 / 50)))
    hi = _sum(t["military"], _prod(_sum(t["maximum"], _prod(_v(-1), t["military"])), _sum(pp, _v(-50)), _v(1 / 50)))
    s.append(' <external_reactions>\n  <force name="thrust" frame="BODY">\n   <function><ifthen><lt>' + pp + _v(50) + '</lt>' + lo + hi
             + f'</ifthen></function>\n   <location unit="IN">{cg}</location>\n   <direction><x>1</x><y>0</y><z>0</z></direction>\n  </force>\n </external_reactions>\n')
    s.append(' <aerodynamics>\n')
    s.append(f'  <function name="thrust/power-pct">{power}</function>\n')
    for k in ("idle", "military", "maximum"):
        s.append(_table("thrust/table/" + k, E[k]["altitude"], E[k]["mach"], E[k]["values"], "position/h-sl-ft", "velocities/mach"))
    for n in ("de", "da", "dr"):
        s.append(f'  <function name="aero/{n}-total-deg">{_sum(_p(f"aero/{ {"de":"elevator","da":"aileron","dr":"rudder"}[n]}-fcs-deg"), _p(f"aero/{n}-direct-deg"))}</function>\n')
    s.append(f'  <function name="aero/abs-beta-deg"><abs>{_p("aero/beta-deg")}</abs></function>\n')
    s.append(f'  <function name="aero/sign-beta"><sign>{_p("aero/beta-deg")}</sign></function>\n')
    a, b_, de = "aero/alpha-deg", "aero/beta-deg", "aero/de-total-deg"
    s.append(_table("aero/table/cx", al, A["cx"]["elevator"], A["cx"]["values"], a, de))
    s.append(_table("aero/table/cm", al, A["cm"]["elevator"], A["cm"]["values"], a, de))
    s.append(_table("aero/table/cl", al, A["cl"]["abs_beta"], A["cl"]["values"], a, "aero/abs-beta-deg"))
    s.append(_table("aero/table/cn", al, A["cn"]["abs_beta"], A["cn"]["values"], a, "aero/abs-beta-deg"))
    for k in ("dlda", "dldr", "dnda", "dndr"):
        s.append(_table("aero/table/" + k, al, A[k]["beta"], A[k]["values"], a, b_))
    s.append(_table("aero/table/cz", al, None, A["cz"]["values"], a))
    for i, name in enumerate(A["damping"]["derivative"]):
        s.append(_table("aero/table/" + name.lower(), al, None, [r[i] for r in A["damping"]["values"]], a))
    # nondimensional rates
    s.append(f'  <function name="aero/pb">{_prod(_p("velocities/p-aero-rad_sec"), _p("aero/bi2vel"))}</function>\n')
    s.append(f'  <function name="aero/qc">{_prod(_p("velocities/q-aero-rad_sec"), _p("aero/ci2vel"))}</function>\n')
    s.append(f'  <function name="aero/rb">{_prod(_p("velocities/r-aero-rad_sec"), _p("aero/bi2vel"))}</function>\n')
    pb, qc, rb = _p("aero/pb"), _p("aero/qc"), _p("aero/rb")
    na, nr = A["control_normalization"]["aileron"], A["control_normalization"]["rudder"]
    cy = A["cy"]
    ctab = lambda n: _p("aero/table/" + n)
    # total coefficients (about the reference point; JSBSim transfers to the CG via AERORP/CG geometry)
    s.append('  <function name="aero/cx-total">' + _sum(ctab("cx"), _prod(ctab("cxq"), qc)) + '</function>\n')
    s.append('  <function name="aero/cy-total">' + _sum(_prod(_v(cy["beta_gain"]), _p(b_)), _prod(_v(cy["aileron_gain"] / na), _p("aero/da-total-deg")),
                                                     _prod(_v(cy["rudder_gain"] / nr), _p("aero/dr-total-deg")), _prod(ctab("cyr"), rb), _prod(ctab("cyp"), pb)) + '</function>\n')
    cz = A["cz"]
    s.append('  <function name="aero/cz-total">' + _sum(
        _prod(ctab("cz"), _sum(_v(1), _prod(_v(-1), _p(b_), _p(b_), _v(1 / cz["beta_scale"] ** 2)))),
        _prod(_v(cz["elevator_gain"] / cz["elevator_scale"]), _p(de)), _prod(ctab("czq"), qc)) + '</function>\n')
    s.append('  <function name="aero/cl-total">' + _sum(_prod(_p("aero/sign-beta"), ctab("cl")), _prod(ctab("dlda"), _p("aero/da-total-deg"), _v(1 / na)),
                                                     _prod(ctab("dldr"), _p("aero/dr-total-deg"), _v(1 / nr)), _prod(ctab("clr"), rb), _prod(ctab("clp"), pb)) + '</function>\n')
    s.append('  <function name="aero/cm-total">' + _sum(ctab("cm"), _prod(ctab("cmq"), qc)) + '</function>\n')
    s.append('  <function name="aero/cn-total">' + _sum(_prod(_p("aero/sign-beta"), ctab("cn")), _prod(ctab("dnda"), _p("aero/da-total-deg"), _v(1 / na)),
                                                     _prod(ctab("dndr"), _p("aero/dr-total-deg"), _v(1 / nr)), _prod(ctab("cnr"), rb), _prod(ctab("cnp"), pb)) + '</function>\n')
    qs = _prod(_p("aero/qbar-psf"), _p("metrics/Sw-sqft"))
    for ax, coef, ref in (("X", "cx", ""), ("Y", "cy", ""), ("Z", "cz", ""), ("ROLL", "cl", "metrics/bw-ft"),
                          ("PITCH", "cm", "metrics/cbarw-ft"), ("YAW", "cn", "metrics/bw-ft")):
        s.append(f'  <axis name="{ax}">\n   <function name="aero/axis/{ax.lower()}">' + _prod(qs, _p(f"aero/{coef}-total"), *([_p(ref)] if ref else [])) + '</function>\n  </axis>\n')
    s.append(' </aerodynamics>\n</fdm_config>\n')
    return "".join(s)


def generate(root, xcg=None):
    root = Path(root)
    d = tomllib.loads(TOML.read_text())
    xcg = d["mass_geometry"]["xcg_ref"]["value"] if xcg is None else xcg
    files = {
        "aircraft/f16_sl/f16_sl.xml": aircraft_xml(d, xcg),
        "engine/dummy.xml": '<?xml version="1.0"?>\n<!-- zero-power engine; exists only so FGTrim can vary fcs/throttle-cmd-norm[0] -->\n'
                            '<electric_engine name="dummy">\n  <power unit="WATTS">0</power>\n</electric_engine>\n',
        "engine/direct.xml": '<?xml version="1.0"?>\n<direct name="Direct">\n</direct>\n',
        "planet/flat_nonrot.xml": '<?xml version="1.0"?>\n<!-- GENERATED. Spherical non-rotating Earth; GM set so g(0) = 9.80665 m/s^2. -->\n'
                                  '<planet name="Earth-sphere-nonrot">\n'
                                  f'  <semimajor_axis unit="FT">{_f(R_FT)}</semimajor_axis>\n  <semiminor_axis unit="FT">{_f(R_FT)}</semiminor_axis>\n'
                                  f'  <rotation_rate unit="RAD/SEC">0.0</rotation_rate>\n  <GM unit="FT3/SEC2">{_f(GM_FT3PS2)}</GM>\n  <J2>0.0</J2>\n</planet>\n',
    }
    for rel, text in files.items():
        p = root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=str(REPO / "reference/jsbsim"))
    ap.add_argument("--xcg", type=float, default=None, help="CG as fraction of cbar (default: xcg_ref, 0.35)")
    a = ap.parse_args()
    generate(a.root, a.xcg)
